const source = await readFile(new URL("../app.js", import.meta.url), "utf8");
const dataBlock = source.slice(source.indexOf("const sections"), source.indexOf("const flatPages"));
const quotedStrings = [...dataBlock.matchAll(/"((?:[^"\\]|\\.)*)"/g)].map((match) =>
  JSON.parse(`"${match[1]}"`),
);

const isTranslatable = (value) => {
  if (!/[A-Za-z]/.test(value)) return false;
  if (/^(https?:|\/|#)/.test(value)) return false;
  if (/^[A-Za-z0-9_-]{6,}$/.test(value) && !value.includes(" ")) return false;
  return true;
};

const strings = [...new Set([...quotedStrings.filter(isTranslatable), ...UI_STRINGS])];
const languages = { hi: "Hindi", kn: "Kannada", bn: "Bengali" };

async function translate(text, target) {
  for (let attempt = 1; attempt <= 3; attempt += 1) {
    try {
      const url = new URL("https://translate.googleapis.com/translate_a/single");
      url.search = new URLSearchParams({
        client: "gtx",
        sl: "en",
        tl: target,
        dt: "t",
        q: text,
      });
      const response = await fetch(url, { signal: AbortSignal.timeout(15000) });
      if (!response.ok) throw new Error(`${target}: ${response.status} for ${text}`);
      const payload = await response.json();
      return payload[0].map((part) => part[0]).join("");
    } catch (error) {
      if (attempt === 3) throw error;
      await new Promise((resolve) => setTimeout(resolve, attempt * 750));
    }
  }
}

async function translateLanguage(code, sourceStrings) {
  const entries = [];
  let cursor = 0;
  const workers = Array.from({ length: 3 }, async () => {
    while (cursor < sourceStrings.length) {
      const index = cursor++;
      const original = sourceStrings[index];
      const translated = await translate(original, code);
      entries[index] = [original, translated];
    }
  });
  await Promise.all(workers);
  return Object.fromEntries(entries);
}

let dictionaries = {};
try {
  ({ translations: dictionaries } = await import(`../translations.js?cache=${Date.now()}`));
} catch {
  dictionaries = {};
}

for (const [code, name] of Object.entries(languages)) {
  dictionaries[code] ||= {};
  const missing = strings.filter((original) => !dictionaries[code][original]);
  process.stdout.write(`Translating ${missing.length} new strings to ${name}...\n`);
  Object.assign(dictionaries[code], await translateLanguage(code, missing));
}

const output = `// Generated by scripts/build-translations.mjs. English source remains in app.js.
export const translations = ${JSON.stringify(dictionaries, null, 2)};
`;
await writeFile(new URL("../translations.js", import.meta.url), output);
process.stdout.write("Wrote translations.js\n");
